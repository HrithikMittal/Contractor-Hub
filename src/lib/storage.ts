// Where document files live:
//  - production: a private Supabase Storage bucket, reached only from the server with the
//    service role key (the browser never gets a storage URL; downloads go through the app)
//  - local development: .data/uploads on disk
// Paths are "<profile id>/<random uuid><ext>", so one person's files never collide with another's.

import fs from "node:fs/promises";
import path from "node:path";
import { resolveEnv } from "./env";
import { DATA_DIR } from "./db";

const LOCAL_DIR = path.join(DATA_DIR, "uploads");

function supabase() {
  const { supabaseUrl, serviceKey, storageBucket, onVercel } = resolveEnv();
  if (supabaseUrl && serviceKey) return { url: supabaseUrl.replace(/\/$/, ""), key: serviceKey, bucket: storageBucket };
  if (onVercel) throw new Error("Document storage is not configured: set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in Vercel.");
  return null;
}

function localPath(storagePath: string) {
  // storagePath is generated by the server; normalise anyway so it can't escape the folder.
  const safe = storagePath.split("/").map((p) => path.basename(p)).join(path.sep);
  return path.join(LOCAL_DIR, safe);
}

export async function putFile(storagePath: string, data: Buffer, contentType: string) {
  const s = supabase();
  if (!s) {
    const p = localPath(storagePath);
    await fs.mkdir(path.dirname(p), { recursive: true });
    await fs.writeFile(p, data);
    return;
  }
  const res = await fetch(`${s.url}/storage/v1/object/${s.bucket}/${storagePath}`, {
    method: "POST",
    headers: { authorization: `Bearer ${s.key}`, apikey: s.key, "content-type": contentType, "x-upsert": "false" },
    body: new Uint8Array(data),
  });
  if (!res.ok) throw new Error(`Upload failed (${res.status}): ${await res.text().catch(() => "")}`);
}

export async function getFile(storagePath: string): Promise<Buffer | null> {
  const s = supabase();
  if (!s) {
    try {
      return await fs.readFile(localPath(storagePath));
    } catch {
      return null;
    }
  }
  const res = await fetch(`${s.url}/storage/v1/object/authenticated/${s.bucket}/${storagePath}`, {
    headers: { authorization: `Bearer ${s.key}`, apikey: s.key },
  });
  if (!res.ok) return null;
  return Buffer.from(await res.arrayBuffer());
}

export async function deleteFiles(storagePaths: string[]) {
  if (storagePaths.length === 0) return;
  const s = supabase();
  if (!s) {
    await Promise.all(storagePaths.map((p) => fs.rm(localPath(p), { force: true })));
    return;
  }
  const res = await fetch(`${s.url}/storage/v1/object/${s.bucket}`, {
    method: "DELETE",
    headers: { authorization: `Bearer ${s.key}`, apikey: s.key, "content-type": "application/json" },
    body: JSON.stringify({ prefixes: storagePaths }),
  });
  if (!res.ok) console.error(`Deleting files failed (${res.status}): ${await res.text().catch(() => "")}`);
}
